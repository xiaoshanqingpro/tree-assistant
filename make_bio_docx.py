txt('标准正态分布 N(0,1)：μ=0, σ=1。任意正态分布可标准化：Z=(X-μ)/σ。')
txt('性质：P(X≥μ)=0.5（关于均值对称）；P(|X-μ|<σ)≈0.6826，P(|X-μ|<2σ)≈0.9544。')
txt('3σ原则：P(|X-μ|<3σ)=0.9974，几乎总取值于(μ-3σ, μ+3σ)之内。')

h3('8.2 均匀分布 U(a,b)')
