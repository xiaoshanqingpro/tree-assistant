txt('方差 D(X)=E(X²)-[E(X)]²：描述离散程度。')
txt('性质：E(aX+b)=aE(X)+b；D(aX+b)=a²D(X)；若X、Y独立，D(X±Y)=D(X)+D(Y)。')

