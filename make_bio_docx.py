h2('第五章 假设检验')

h3('1. 假设检验的基本思想')
txt('利用小概率反证法思想：从问题的对立面(H0)出发，间接判断要解决的问题(H1)是否成立。在H0成立的条件下计算检验统计量，根据P值作出推断。')
txt('小概率原理：一个事件发生的概率很小（≤0.05或0.01），在一次试验中几乎不可能发生。')

h3('2. 假设检验的步骤')
txt('(1) 建立原假设H0及备择假设H1（两个假设总是成对出现）')
txt('(2) 构造检验统计量（如Z、t、F、χ²等）')
txt('(3) 确定H0的拒绝域（根据显著性水平α）')
txt('(4) 计算统计量值，根据抽样结果作结论（P<α则拒绝H0）')

h3('3. 原假设与备择假设')
txt('原假设H0：待检验的假设，通常表示"没有差异"或"无效果"。')
txt('备择假设H1：与原假设对立的假设，表示"有差异"或"有效果"。')
txt('两者同时出现，结论为二者选其一。')

h3('4. 单侧检验 vs 双侧检验')
txt('双侧检验：H0: μ=μ0，H1: μ≠μ0，拒绝域在两侧。')
txt('右侧检验：H0: μ≤μ0，H1: μ>μ0，拒绝域在右侧。')
txt('左侧检验：H0: μ≥μ0，H1: μ<μ0，拒绝域在左侧。')
txt('判断方法：看备择假设H1的方向——>为右尾，<为左尾。')

h3('5. 两类错误')
txt('第一类错误（α错误，"弃真"）：H0为真时拒绝H0。')
txt('第二类错误（β错误，"取伪"）：H0为假时接受H0。')
txt('关系：α越小则β越大，反之亦然。通常α取0.05或0.01。')
txt('1-α称为可靠性（置信水平），1-β称为检验功效（把握度）。')
txt('降低两类错误的措施：选取适当的α和增加试验重复次数n。')

h3('6. P值')
txt('P值就是风险（拒绝H0时可能犯错误的风险）的临界值。')
txt('当P<α时，拒绝H0（差异显著）；当P>α时，接受H0（差异不显著）。')

h3('7. 总体平均数的假设检验')
txt('大样本且σ已知：Z检验。Z=(x̄-μ0)/(σ/√n)')
txt('小样本且σ未知：t检验。t=(x̄-μ0)/(s/√n)，自由度df=n-1')

h3('8. 方差齐性检验（F检验）')
txt('F = S1²/S2²（较大方差放在分子）。比较两个总体的方差是否相同。')
txt('当两样本总体均服从正态分布、两样本随机且独立时，F值服从F分布。')

h3('9. 配对数据的t检验')
