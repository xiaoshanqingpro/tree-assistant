txt('概率公式：P(X=k) = λ^k·e^(-λ) / k!')
txt('期望 E(X)=λ，方差 D(X)=λ')
txt('典型应用：变异植株出现概率、放射性衰变计数、单位面积内的昆虫数。')

h3('8. 连续型随机变量分布')

