h2('第二章 概率和概率分布')

h3('1. 随机现象与随机试验')
txt('确定性现象：在一定条件下必然发生的现象（如向上抛出的物体在地球上会落下）。')
txt('随机现象：在一定条件下可能发生也可能不发生的现象。')
txt('随机试验的三个特征：(1) 相同条件下可重复进行；(2) 事先知道所有可能结果；(3) 进行前不知道哪个结果会发生。')

h3('2. 样本空间与事件')
txt('样本空间：随机试验的所有可能结果构成的集合，记为U={e}。')
txt('随机事件：样本空间的子集。基本事件：只包含一个样本点的事件。')

h3('3. 古典概型')
txt('P(A) = 事件A包含的样本点数 / 样本空间总样本点数')
txt('条件：有限个样本点，每个样本点等可能。')

h3('4. 几何概型')
txt('P(A) = 构成事件A的测度（长度/面积/体积）/ 样本空间的测度')
txt('适用于样本空间无限且均匀分布的情形。经典题型：会面问题、等车问题。')

h3('5. 概率基本公式')
txt('加法定理：P(A∪B) = P(A) + P(B) - P(AB)。若A、B互不相容，P(AB)=0，则P(A∪B)=P(A)+P(B)。')
txt('条件概率：P(B|A) = P(AB)/P(A)，其中P(A)>0。')
txt('乘法定理：P(AB) = P(A)·P(B|A) = P(B)·P(A|B)。')
txt('全概率公式：P(B) = ΣP(Ai)·P(B|Ai)。')
txt('贝叶斯公式：P(Ai|B) = P(Ai)·P(B|Ai) / ΣP(Aj)·P(B|Aj)。')

h3('6. 事件的独立性')
txt('若P(AB) = P(A)·P(B)，则A、B相互独立。此时P(A|B)=P(A)。')
txt('互斥(不相容)与独立是不同的概念：互斥指A∩B=Ø，独立指概率乘积关系。')

h3('7. 离散型随机变量分布')
h3('7.1 二项分布 X~B(n,p)')
txt('适用条件：n次独立重复试验，每次试验只有两种结果（成功/失败），每次成功概率p不变。')
txt('概率公式：P(X=k) = C(n,k)·p^k·(1-p)^(n-k)')
txt('期望 E(X)=np，方差 D(X)=np(1-p)')
